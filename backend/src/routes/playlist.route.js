import { Router } from "express";
import { protectRoute } from "../middleware/auth.middleware.js";
import { addCollaborator, addSong, createPlaylist, deletePlaylist, getMyPlaylists, getPlaylistById, removeCollaborator, removeSong, reorderPlaylistSongs, setPlaylistDownloaded, updatePlaylist } from "../controller/playlist.controller.js";
import { generatePlaylist } from "../controller/playlistGenerator.controller.js";
import { rateLimit } from "../middleware/rateLimit.middleware.js";
const router = Router();
router.use(protectRoute);
router.get("/", getMyPlaylists);
router.post("/generate", rateLimit({ name: "ai-playlist-generator", limit: 5, windowMs: 60 * 60 * 1000 }), generatePlaylist);
router.get("/:playlistId", getPlaylistById);
router.post("/", createPlaylist);
router.put("/:playlistId", updatePlaylist);
router.delete("/:playlistId", deletePlaylist);
router.put("/:playlistId/download", setPlaylistDownloaded);
router.post("/:playlistId/collaborators", addCollaborator);
router.delete("/:playlistId/collaborators/:userId", removeCollaborator);
router.put("/:playlistId/songs/reorder", reorderPlaylistSongs);
router.post("/:playlistId/songs", addSong);
router.delete("/:playlistId/songs/:songId", removeSong);
export default router;
